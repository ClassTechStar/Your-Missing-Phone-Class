def fix_glue(text: str, table: dict) -> tuple:
    """把粘连词替换为带空格的形式。返回 (新文本, 命中次数)。"""
    n = 0
    for bad, good in table.items():
        if bad in GLUE_EL_KEEP:
            continue
        c = text.count(bad)
        if c:
            n += c
            text = text.replace(bad, good)
    return text, n


# ---------------------------------------------------------------- 标点规范化（仅 el）
RE_DQ = re.compile(r'""+')                       # 连续空引号
# 希腊字母紧贴引号（`εμφάνιση"Κωδικός"`）：机器翻译把两个 UI 标签拼在一起，
# 引号前补空格；引号内是正常词组（前后已有空格）的不受影响。
RE_GREEK_QUOTE = re.compile(f'([{GL}])"([^"\n]{{0,60}})"')
# 希腊语缩写点（κ.ά. / π.χ.）不能当成损坏的句点
RE_GK_ABBR = re.compile(f'[{GL}]\\.')
_ABBR_MARK = '\x00'


def fix_punct(text: str) -> tuple:
    """规范化损坏的连写标点与希腊字母间的直引号。返回 (新文本, 统计)。

    注意：空引号（`""`）**不删不合并** —— 合并会改变引号个数，
    LaTeX 侧按成对引号配对成中文弯引号，数量一变就会出现反向引号。
    空引号只是内容缺失的痕迹，不影响折行，留着即可。
    """
    stats = {'dq': 0, 'comma': 0, 'quote': 0}
    out = text

    # 保护希腊语缩写点（κ.ά. / π.χ.）
    out = RE_GK_ABBR.sub(lambda m: m.group(0)[:-1] + _ABBR_MARK, out)

    # 连写逗号/分号 → 单个 + 空格
    def _multi(m):
        stats['comma'] += 1
        return m.group(1) + ' '
    out = re.sub(r'([,;])(?:[,;]+)', _multi, out)
    # 句点与逗号/分号连写（`.,` / `,.`）→ 句点 + 空格
    out = re.sub(r'\.([,;])(?![,;])',
                 lambda m: (stats.__setitem__('comma', stats['comma'] + 1), '. ')[1], out)
    out = re.sub(r'([,;])\.(?![.\d])',
                 lambda m: (stats.__setitem__('comma', stats['comma'] + 1), '. ')[1], out)

    out = out.replace(_ABBR_MARK, '.')

    # 希腊字母紧贴引号 → 引号前补空格；引号后紧跟括号也补空格
    def _q(m):
        stats['quote'] += 1
        return m.group(1) + ' "' + m.group(2) + '"'
    out = RE_GREEK_QUOTE.sub(_q, out)
    out = re.sub(r'"(?=[(\[{])', '" ', out)
    out = re.sub(r'  +', ' ', out)
    return out, stats


def process(path: Path, is_el: bool, apply: bool) -> dict:
    raw = path.read_text(encoding='utf-8')
    stats = {'glue': 0, 'dq': 0, 'comma': 0, 'quote': 0, 'nodes': 0}

    def repl(m):
        t = m.group(1)
        if '{' in t or 'function' in t or '<' in t:
            return m.group(0)
        new, g = fix_glue(t, GLUE_EL)
        dq = cm = qt = 0
        if is_el:
            new, ps = fix_punct(new)
            dq, cm, qt = ps['dq'], ps['comma'], ps['quote']
        if g or dq or cm or qt:
            stats['glue'] += g
            stats['dq'] += dq
            stats['comma'] += cm
            stats['quote'] += qt
            stats['nodes'] += 1
            return '>' + new + '<'
        return m.group(0)

    out = RE_TEXT.sub(repl, raw)
    changed = out != raw
    if apply and changed:
        path.write_text(out, encoding='utf-8', newline='')
    stats['changed'] = changed
    return stats


def main():
    apply = '--apply' in sys.argv
    only = [a for a in sys.argv[1:] if not a.startswith('--')]
    targets = []
    for dirpath, dirs, files in os.walk(REPO):
        if '.git' in dirpath:
            continue
        for f in sorted(files):
            if f.endswith('.html'):
                targets.append(Path(dirpath) / f)
    total = {'glue': 0, 'dq': 0, 'comma': 0, 'quote': 0, 'nodes': 0, 'files': 0}
    for p in targets:
        if only and not any(o in str(p) for o in only):
            continue
        is_el = p.stem.lower() in ('el',) or 'el.html' in p.name.lower()
        s = process(p, is_el, apply)
        if s['changed']:
            total['glue'] += s['glue']
            total['dq'] += s['dq']
            total['comma'] += s['comma']
            total['quote'] += s['quote']
            total['nodes'] += s['nodes']
            total['files'] += 1
            print(f"{str(p).replace(str(REPO), ''):34s} 粘连={s['glue']:4d} "
                  f"空引号={s['dq']:4d} 连写标点={s['comma']:4d} 引号粘连={s['quote']:4d} "
                  f"节点={s['nodes']:3d} {'已写盘' if apply else '待写'}")
    print(f"\n合计: 文件 {total['files']}，粘连 {total['glue']}，空引号 {total['dq']}，"
          f"连写标点 {total['comma']}，引号粘连 {total['quote']}，节点 {total['nodes']}"
          + ('（已写盘）' if apply else '（干跑，未写盘）'))


if __name__ == '__main__':
    main()
